import pg from 'pg';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { drizzle, type NodePgDatabase } from 'drizzle-orm/node-postgres';
import * as schema from './schema';
import { getDatabaseUrl } from './index';

const { Client, Pool } = pg;
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const MIGRATIONS_DIR = path.resolve(__dirname, '../../drizzle');

export interface TestDatabaseContext {
  db: NodePgDatabase<typeof schema>;
  client: pg.Client;
  schemaName: string;
  cleanup: () => Promise<void>;
}

/**
 * Checks whether PostgreSQL is reachable with a short timeout.
 */
export async function isPostgresReachable(url?: string): Promise<boolean> {
  const targetUrl = url || getDatabaseUrl();
  const isRemote =
    targetUrl.includes('supabase.co') ||
    targetUrl.includes('pooler.supabase.com') ||
    targetUrl.includes('sslmode=require') ||
    process.env.DB_SSL === 'true';
  const client = new Client({
    connectionString: targetUrl,
    connectionTimeoutMillis: 5000,
    ...(isRemote ? { ssl: { rejectUnauthorized: false } } : {}),
  });

  let timeoutId: NodeJS.Timeout | null = null;
  const timeoutPromise = new Promise<never>((_, reject) => {
    timeoutId = setTimeout(() => reject(new Error('Postgres reachability timeout')), 5000);
  });

  try {
    await Promise.race([
      (async () => {
        await client.connect();
        await client.query('SELECT 1;');
        await client.end();
      })(),
      timeoutPromise,
    ]);
    return true;
  } catch {
    try {
      await client.end().catch(() => {});
    } catch {
      // ignore cleanup errors
    }
    return false;
  } finally {
    if (timeoutId) clearTimeout(timeoutId);
  }
}

/**
 * Creates an isolated PostgreSQL schema for tests, applies all migrations cleanly into it,
 * and provides a cleanup function that drops the schema cascade.
 */
export async function createTestContext(connectionUrl?: string): Promise<TestDatabaseContext> {
  const url = connectionUrl || getDatabaseUrl();
  const isRemote =
    url.includes('supabase.co') ||
    url.includes('pooler.supabase.com') ||
    url.includes('sslmode=require') ||
    process.env.DB_SSL === 'true';

  const client = new Client({
    connectionString: url,
    connectionTimeoutMillis: 5000,
    ...(isRemote ? { ssl: { rejectUnauthorized: false } } : {}),
  });

  try {
    await client.connect();
  } catch (err: unknown) {
    const errorMsg =
      `[TestHelper] Cannot connect to PostgreSQL at ${url}. ` +
      `Docker is required to run server database tests. ` +
      `Start the local database with 'docker compose up -d' in Windows PowerShell. ` +
      `Original error: ${err instanceof Error ? err.message : String(err)}`;
    throw new Error(errorMsg);
  }

  // Generate unique isolated schema name
  const schemaName = `test_${crypto.randomUUID().replace(/-/g, '_')}`;

  // 1. Create schema and set search path
  await client.query(`CREATE SCHEMA "${schemaName}";`);
  await client.query(`SET search_path TO "${schemaName}", public;`);

  // 2. Apply all migration SQL files sequentially into this schema
  const sqlFiles = fs
    .readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith('.sql'))
    .sort();

  for (const file of sqlFiles) {
    const fullPath = path.join(MIGRATIONS_DIR, file);
    const sqlContent = fs.readFileSync(fullPath, 'utf8');
    // Ensure foreign key references target the isolated test schema instead of hardcoded "public"
    const schemaSql = sqlContent.replaceAll('"public".', `"${schemaName}".`);

    // Split by statement-breakpoint if generated by drizzle-kit
    const statements = schemaSql
      .split('--> statement-breakpoint')
      .map((s) => s.trim())
      .filter((s) => s.length > 0);

    for (const stmt of statements) {
      await client.query(stmt);
    }
  }

  const pool = new Pool({
    connectionString: url,
    connectionTimeoutMillis: 5000,
    max: 10,
    options: `-c search_path="${schemaName}",public`,
    ...(isRemote ? { ssl: { rejectUnauthorized: false } } : {}),
  });

  const db = drizzle(pool, { schema });

  const cleanup = async () => {
    try {
      await client.query(`DROP SCHEMA IF EXISTS "${schemaName}" CASCADE;`);
    } catch (e) {
      console.warn(`[TestHelper] Warning: Failed to drop schema ${schemaName}:`, e);
    } finally {
      await pool.end().catch(() => {});
      await client.end().catch(() => {});
    }
  };

  return {
    db,
    client,
    schemaName,
    cleanup,
  };
}
